from collections.abc import Callable
from datetime import UTC, datetime
import hashlib
import json
import os
from pathlib import Path
import sys
from typing import Any

import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from scripts.experiment8 import reference_policy_probe as reference_probe
from scripts.experiment8 import serve_submodule_policy as paired_noise

# Reuse the paired diagnostic's shared provenance/noise APIs and the reference
# probe's explicit Orbax-action conversion helpers by design.
# ruff: noqa: E402, I001, SLF001

DEFAULT_JAX_CHECKPOINT_DIR = reference_probe.DEFAULT_JAX_CHECKPOINT
DEFAULT_TRANSFORM_CHECKPOINT_DIR = reference_probe.DEFAULT_TRITON_BASE
ACTION_SPACE = paired_noise.ACTION_SPACE
ACTION_HORIZON = reference_probe.ACTION_HORIZON
ACTION_DIM = reference_probe.ACTION_DIM
OUTPUT_ACTION_DIM = reference_probe.OUTPUT_ACTION_DIM
DENOISE_STEPS = reference_probe.NUM_STEPS
RUNTIME_NAME = "jax_reference"
RUNTIME_IMPLEMENTATION = "official_jax_reference"


def _set_jax_preallocation_disabled() -> None:
    """Must run before importing JAX/OpenPI modules that initialize JAX."""
    os.environ["XLA_PYTHON_CLIENT_PREALLOCATE"] = "false"


def _tree_identity(directory: Path) -> dict[str, Any]:
    """Hash every regular file in an Orbax directory with stable-file checks."""
    root = directory.expanduser().resolve(strict=True)
    if not root.is_dir():
        raise ValueError(f"Orbax params path is not a directory: {root}")
    before: list[Path] = []
    for path in root.rglob("*"):
        if path.is_symlink():
            raise ValueError(f"Refusing symlinks inside Orbax params: {path}")
        if path.is_file():
            before.append(path)
    before.sort(key=lambda path: path.relative_to(root).as_posix())
    required = {"_METADATA", "manifest.ocdbt", "ocdbt.process_0/manifest.ocdbt"}
    missing = sorted(required - {path.relative_to(root).as_posix() for path in before})
    if missing:
        raise ValueError(f"Orbax params directory is missing expected files: {missing}")

    files: list[dict[str, Any]] = []
    total_size = 0
    for path in before:
        identity = paired_noise._file_identity(path)
        relative = path.relative_to(root).as_posix()
        entry = {
            "relative_path": relative,
            "size_bytes": identity["size_bytes"],
            "sha256": identity["sha256"],
        }
        files.append(entry)
        total_size += identity["size_bytes"]

    after: list[Path] = []
    for path in root.rglob("*"):
        if path.is_symlink():
            raise RuntimeError(f"Orbax params tree changed to include a symlink while hashing: {path}")
        if path.is_file():
            after.append(path)
    after.sort(key=lambda path: path.relative_to(root).as_posix())
    if [p.relative_to(root).as_posix() for p in before] != [p.relative_to(root).as_posix() for p in after]:
        raise RuntimeError(f"Orbax params file list changed while hashing: {root}")

    manifest_bytes = paired_noise._canonical_json_bytes(files)
    return {
        "path": str(root),
        "format": "Orbax OCDBT checkpoint directory",
        "file_count": len(files),
        "total_size_bytes": total_size,
        "sha256": hashlib.sha256(manifest_bytes).hexdigest(),
        "files": files,
    }


def _build_run_provenance(
    *,
    params_dir: Path,
    checkpoint_norm_stats_path: Path,
    transform_norm_stats_path: Path,
    source_script_path: Path,
    runtime_config: dict[str, Any],
) -> dict[str, Any]:
    params = _tree_identity(params_dir)
    checkpoint_norm = paired_noise._file_identity(checkpoint_norm_stats_path)
    transform_norm = paired_noise._file_identity(transform_norm_stats_path)
    if checkpoint_norm["sha256"] != transform_norm["sha256"]:
        raise ValueError(
            "Raw JAX checkpoint and reference-probe transform norm_stats differ: "
            f"raw={checkpoint_norm['sha256']}, transform={transform_norm['sha256']}"
        )
    source = paired_noise._file_identity(source_script_path)
    runtime_config_json = json.loads(paired_noise._canonical_json_bytes(runtime_config))
    provenance: dict[str, Any] = {
        "schema_version": 1,
        "recorded_at_utc": datetime.now(UTC).isoformat(timespec="seconds"),
        "runtime": RUNTIME_NAME,
        "checkpoint_path": params["path"],
        "checkpoint_sha256": params["sha256"],
        "checkpoint_size_bytes": params["total_size_bytes"],
        "params_format": params["format"],
        "params_file_count": params["file_count"],
        "params_files": params["files"],
        "params_metadata_sha256": next(
            item["sha256"] for item in params["files"] if item["relative_path"] == "_METADATA"
        ),
        "params_ocdbt_manifest_sha256": {
            item["relative_path"]: item["sha256"]
            for item in params["files"]
            if item["relative_path"].endswith("manifest.ocdbt")
        },
        "norm_stats_path": transform_norm["path"],
        "norm_stats_sha256": transform_norm["sha256"],
        "norm_stats_size_bytes": transform_norm["size_bytes"],
        "raw_checkpoint_norm_stats_path": checkpoint_norm["path"],
        "raw_checkpoint_norm_stats_sha256": checkpoint_norm["sha256"],
        "transform_norm_stats_match_raw_checkpoint": True,
        "source_script_path": source["path"],
        "source_script_sha256": source["sha256"],
        "source_script_size_bytes": source["size_bytes"],
        "runtime_config": runtime_config_json,
    }
    provenance["provenance_sha256"] = paired_noise._provenance_digest(provenance)
    paired_noise._verify_run_provenance(provenance)
    return provenance


def _publish_run_provenance(path: Path, provenance: dict[str, Any]) -> Path:
    """Use the diagnostic server's verified atomic, no-overwrite publisher."""
    return paired_noise._publish_run_metadata(path, provenance)


class OfficialJaxReferencePolicy(paired_noise.BasePolicy):
    """Websocket policy with request-key noise and the original JAX sampler."""

    def __init__(
        self,
        *,
        input_transform: Callable[[dict[str, Any]], dict[str, Any]],
        output_transform: Callable[[dict[str, Any]], dict[str, Any]],
        action_runner: Callable[[dict[str, Any], np.ndarray], Any],
        run_provenance: dict[str, Any],
    ) -> None:
        self._input_transform = input_transform
        self._output_transform = output_transform
        self._action_runner = action_runner
        self._run_provenance = json.loads(paired_noise._canonical_json_bytes(run_provenance))
        paired_noise._verify_run_provenance(self._run_provenance)
        self.metadata = {
            "policy_type": "pi0_libero_official_jax_reference",
            "runtime": RUNTIME_NAME,
            "runtime_implementation": RUNTIME_IMPLEMENTATION,
            "eager_diagnostic": False,
            "production_latency_claim": False,
            "vlm_layer_pattern": "vlm_full18",
            "action_layer_pattern": "full18",
            "denoise_steps": DENOISE_STEPS,
            "skip_attn_layers": [],
            "skip_ffn_layers": [],
            "action_space": ACTION_SPACE,
            "run_provenance": self._run_provenance,
        }

    def reset(self) -> None:
        """The official JAX sampler has no per-episode inference state here."""

    def infer(self, obs: dict[str, Any]) -> dict[str, Any]:
        if not isinstance(obs, dict):
            raise TypeError(f"Expected an observation dict, got {type(obs)!r}")
        noise, noise_source, identity = paired_noise._extract_noise(
            obs, action_horizon=ACTION_HORIZON, action_dim=ACTION_DIM
        )
        required = ("observation/image", "observation/wrist_image", "observation/state", "prompt")
        missing = [key for key in required if key not in obs]
        if missing:
            raise ValueError(f"Missing policy observation fields: {', '.join(missing)}")
        inputs = {key: paired_noise._copy_observation_tree(obs[key]) for key in required}
        if not str(inputs["prompt"]):
            raise ValueError("prompt must not be empty")

        transformed = self._input_transform(inputs)
        # Triton's existing input preparer casts its seed noise to BF16. Pass
        # those exact numeric values to JAX to isolate implementation effects.
        effective_noise = reference_probe._float32_to_bfloat16_roundtrip(noise)
        raw_actions = reference_probe._to_numpy_actions(self._action_runner(transformed, effective_noise))
        actions = reference_probe._transform_policy_actions(
            raw_actions=raw_actions,
            transformed=transformed,
            output_transform=self._output_transform,
        )
        diagnostic_metadata = {
            "runtime": RUNTIME_NAME,
            "runtime_implementation": RUNTIME_IMPLEMENTATION,
            "jax_reference": True,
            "noise_sha256": hashlib.sha256(noise.tobytes(order="C")).hexdigest(),
            "effective_noise_bfloat16_sha256": reference_probe.sha256_array(effective_noise),
            "noise_shape": list(noise.shape),
            "noise_source": noise_source,
            "noise_identity": identity,
            "skip_attn_layers": [],
            "skip_ffn_layers": [],
            "denoise_steps": DENOISE_STEPS,
            "action_space": ACTION_SPACE,
            "eager_diagnostic": False,
            "latency_note": "Official JAX reference path; not the eager Triton diagnostic and not a production-latency claim.",
            "vlm_layer_pattern": "vlm_full18",
            "action_layer_pattern": "full18",
            "run_provenance": self._run_provenance,
            "provenance_sha256": self._run_provenance["provenance_sha256"],
        }
        return {"actions": actions, "diagnostic_metadata": diagnostic_metadata}


def _make_jax_action_runner(
    *, jax: Any, jnp: Any, model_lib: Any, sampler: Callable[..., Any], device: Any
) -> Callable[[dict[str, Any], np.ndarray], Any]:
    """Build the batched unmodified ``Pi0.sample_actions`` call (JIT as policy does)."""

    def run(transformed: dict[str, Any], effective_noise: np.ndarray) -> Any:
        with jax.default_device(device):
            batched = jax.tree.map(
                lambda value: jax.device_put(jnp.asarray(value)[np.newaxis, ...], device), transformed
            )
            observation = model_lib.Observation.from_dict(batched)
            # Match openpi.policies.policy.Policy's default key and split.
            _, sample_rng = jax.random.split(jax.random.key(0))
            noise = jax.device_put(jnp.asarray(effective_noise, dtype=jnp.float32)[np.newaxis, ...], device)
            return sampler(sample_rng, observation, num_steps=DENOISE_STEPS, noise=noise)

    return run


def _asset_id(train_config: Any) -> str:
    data_config = train_config.data
    asset_id = getattr(data_config, "asset_id", None)
    if not isinstance(asset_id, str) or not asset_id:
        assets_config = getattr(data_config, "assets", None)
        asset_id = getattr(assets_config, "asset_id", None)
    if not isinstance(asset_id, str) or not asset_id:
        repo_id = getattr(data_config, "repo_id", None)
        asset_id = repo_id if isinstance(repo_id, str) and repo_id else None
    if asset_id is None:
        raise ValueError("pi0_libero has no resolvable data asset_id for normalization provenance")
    return asset_id


def build_argument_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--jax-checkpoint-dir", type=Path, default=DEFAULT_JAX_CHECKPOINT_DIR)
    parser.add_argument("--transform-checkpoint-dir", type=Path, default=DEFAULT_TRANSFORM_CHECKPOINT_DIR)
    parser.add_argument("--run-metadata-path", type=Path, required=True)
    parser.add_argument("--host", default="0.0.0.0")
    parser.add_argument("--port", type=int, default=8028)
    parser.add_argument(
        "--jax-device",
        default="gpu:0",
        help="JAX device, e.g. gpu:0 or cpu:0; use CUDA_VISIBLE_DEVICES to select the physical GPU",
    )
    return parser


def _select_jax_device(jax: Any, selector: str) -> Any:
    if ":" in selector:
        platform, index_text = selector.split(":", maxsplit=1)
        if platform not in ("gpu", "cpu", "tpu") or not index_text.isdecimal():
            raise ValueError("--jax-device must be default or one of gpu:N, cpu:N, tpu:N")
        devices = jax.devices(platform)
        index = int(index_text)
        if index >= len(devices):
            raise ValueError(f"Requested {selector}, but only {len(devices)} {platform} device(s) are visible")
        return devices[index]
    if selector != "default":
        raise ValueError("--jax-device must be default or one of gpu:N, cpu:N, tpu:N")
    devices = jax.devices()
    if not devices:
        raise RuntimeError("JAX reports no default devices")
    return devices[0]


def create_server(args: argparse.Namespace) -> Any:
    """Publish provenance, load official Orbax JAX model, and build websocket server."""
    _set_jax_preallocation_disabled()
    checkpoint_dir = args.jax_checkpoint_dir.expanduser().resolve(strict=True)
    transform_checkpoint_dir = args.transform_checkpoint_dir.expanduser().resolve(strict=True)
    params_dir = checkpoint_dir / "params"
    checkpoint_norm = checkpoint_dir / "assets/physical-intelligence/libero/norm_stats.json"
    if not params_dir.is_dir():
        raise FileNotFoundError(f"Orbax params directory does not exist: {params_dir}")

    # Hash and publish the no-overwrite startup record before importing/loading
    # the model, matching the paired server's evidence-first startup contract.
    metadata_target = paired_noise._resolve_run_metadata_target(args.run_metadata_path)
    assert metadata_target is not None
    asset_norm_path = transform_checkpoint_dir / "assets/physical-intelligence/libero/norm_stats.json"
    runtime_config = {
        "runtime": RUNTIME_NAME,
        "runtime_implementation": RUNTIME_IMPLEMENTATION,
        "policy_type": "pi0_libero_official_jax_reference",
        "config_name": "pi0_libero",
        "host": str(args.host),
        "port": int(args.port),
        "jax_device_selector": str(args.jax_device),
        "jax_preallocate": False,
        "sample_method": "official Pi0.sample_actions",
        "denoise_steps": DENOISE_STEPS,
        "action_horizon": ACTION_HORIZON,
        "action_dim": ACTION_DIM,
        "output_action_dim": OUTPUT_ACTION_DIM,
        "vlm_layer_pattern": "vlm_full18",
        "action_layer_pattern": "full18",
        "skip_attn_layers_1based": [],
        "skip_ffn_layers_1based": [],
        "noise_source": "serve_submodule_policy._extract_noise request-key deterministic seed",
        "noise_effective_quantization": "BF16 round-to-nearest-even values, represented as float32 for JAX call",
        "input_output_transform_source": str(transform_checkpoint_dir),
    }
    provenance = _build_run_provenance(
        params_dir=params_dir,
        checkpoint_norm_stats_path=checkpoint_norm,
        transform_norm_stats_path=asset_norm_path,
        source_script_path=Path(__file__),
        runtime_config=runtime_config,
    )
    _publish_run_provenance(metadata_target, provenance)

    sys.path.insert(0, str(REPO_ROOT))
    sys.path.insert(0, str(REPO_ROOT / "scripts/spec"))
    import jax
    import jax.numpy as jnp
    import spec_serve_policy

    import openpi.models.model as model_lib
    from openpi.serving.websocket_policy_server import WebsocketPolicyServer
    from openpi.shared import nnx_utils
    from openpi.training import config as train_config_lib

    official_config = train_config_lib.get_config("pi0_libero")
    if type(official_config.model).__name__ != "Pi0Config":
        raise TypeError(f"Expected official pi0_libero Pi0Config, got {type(official_config.model).__name__}")
    train_config, input_transform, output_transform = spec_serve_policy._build_policy_components(
        config_name="pi0_libero", checkpoint_dir=transform_checkpoint_dir
    )
    if int(train_config.model.action_horizon) != ACTION_HORIZON or int(train_config.model.action_dim) != ACTION_DIM:
        raise ValueError("Official pi0_libero config does not match the expected 50x32 raw action shape")
    device = _select_jax_device(jax, args.jax_device)
    with jax.default_device(device):
        params = model_lib.restore_params(params_dir, dtype=jnp.bfloat16)
        model = official_config.model.load(params)
    sampler = nnx_utils.module_jit(model.sample_actions)
    action_runner = _make_jax_action_runner(jax=jax, jnp=jnp, model_lib=model_lib, sampler=sampler, device=device)
    policy = OfficialJaxReferencePolicy(
        input_transform=input_transform,
        output_transform=output_transform,
        action_runner=action_runner,
        run_provenance=provenance,
    )
    return WebsocketPolicyServer(policy=policy, host=args.host, port=args.port, metadata=policy.metadata)


def main(argv: list[str] | None = None) -> int:
    _set_jax_preallocation_disabled()
    args = build_argument_parser().parse_args(argv)
    if not 1 <= args.port <= 65535:
        raise ValueError("port must be in 1..65535")
    server = create_server(args)
    print(
        json.dumps(
            {
                "host": args.host,
                "port": args.port,
                "runtime": RUNTIME_NAME,
                "eager_diagnostic": False,
                "jax_preallocate": False,
                "skip_attn_layers": [],
                "skip_ffn_layers": [],
            },
            ensure_ascii=False,
        ),
        flush=True,
    )
    server.serve_forever()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
