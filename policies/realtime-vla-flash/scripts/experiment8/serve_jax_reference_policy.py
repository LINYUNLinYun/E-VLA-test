#!/usr/bin/env python3
"""Serve the unmodified official JAX pi0_libero policy for paired rollouts.

The websocket input matches ``run_submodule_rollout.py``. Request-key-derived
noise is generated by the same helper as the Triton diagnostic server, then
rounded to the BF16 values consumed by Triton before JAX ``sample_actions`` is
called. This is an implementation-reference runtime, not an eager Triton
diagnostic and not a production-latency claim.
"""

from __future__ import annotations

