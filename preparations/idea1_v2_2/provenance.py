"""Shared, deterministic scientific source and preprocessing asset receipts."""
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]

def receipt(path):
    path=Path(path).resolve()
    h=hashlib.sha256()
    with path.open('rb') as f:
        for block in iter(lambda:f.read(8*1024*1024),b''): h.update(block)
    return dict(path=str(path),sha256=h.hexdigest())

def collect_checkpoint_assets(model_id,checkpoint):
    """Hash all tokenizer/processor/code/config assets, never weight shards."""
    checkpoint=Path(checkpoint)
    directory=checkpoint.parent if checkpoint.is_file() else checkpoint
    assets={}
    for path in sorted(directory.rglob('*')):
        if path.is_file() and path.suffix in ('.json','.py','.txt','.jinja','.model','.bpe') and path.name!='README.md':
            assets[str(path.resolve())]=receipt(path)
    if model_id=='pi0':
        # These four manifests and their embedding tensors are read by the
        # actual Backend constructor, not regenerated by a tokenizer.
        for artifact in ('draft_spatial','draft_object','draft','draft_10'):
            manifest=directory.parent/artifact/'manifest.json'
            assets[str(manifest.resolve())]=receipt(manifest)
            for entry in json.loads(manifest.read_text())['prompts'].values():
                path=manifest.parent/entry['embed_path']
                assets[str(path.resolve())]=receipt(path)
    elif model_id=='db-cogact':
        # Native vision.load_model reads the local CLIP processor config.
        hub=ROOT/'shared/caches/huggingface/hub'
        for snapshot in ('models--openai--clip-vit-large-patch14-336/snapshots/ce19dc912ca5cd21c8a653c79e251e808ccabcd1',
                         'models--Qwen--Qwen2.5-7B/snapshots/d149729398750b98c0af14eb82c78cfe92750796'):
            for path in sorted((hub/snapshot).glob('*.json')):
                assets[str(path.resolve())]=receipt(path)
    return assets

def collect_scientific_sources(model_id):
    """Conservative source closure shared by freeze and runtime.

    Includes the entire local model/transform package where import routing can
    select helper functions, so imported scientific code cannot escape hashing.
    No result files, tests, or checkpoint weight shards enter this closure.
    """
    paths=[ROOT/'preparations/idea1_v2_1/runtime_models.py',ROOT/'preparations/idea1_v2_1/adapters.py']
    paths += [Path(__file__).with_name(n) for n in ('runtime_models.py','schedules.py','pi0_adapter.py','provenance.py')]
    if model_id=='pi0':
        project=ROOT/'policies/realtime-vla-flash'
        paths += [project/p for p in ('scripts/experiment10/backend.py','scripts/experiment10/common.py',
            'scripts/experiment1/run_intermediate_action_probe.py','scripts/spec/spec_serve_policy.py')]
        paths += list((project/'scripts/spec/triton').rglob('*.py'))
        paths += list((project/'src/openpi').rglob('*.py'))
    elif model_id=='db-cogact':
        paths += list((ROOT/'policies/db-cogact/dexbotic').rglob('*.py'))
    if model_id in ('xiaomi-robotic0','db-cogact'):
        verification=json.loads((ROOT/f'preparations/idea1_v2_1/metadata/{model_id}/weights_verified.json').read_text())
        paths += list(Path(verification['checkpoint']).glob('*.py'))
    return {str(path.relative_to(ROOT)):receipt(path)['sha256'] for path in sorted(set(paths))}
